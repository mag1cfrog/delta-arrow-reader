def requests():
    manifest = read(MANIFEST)
    corpora = []
    fields = [{"name": name, "type": "integer", "nullable": False, "metadata": {}} for name in ("id", "k")]
    for shape in manifest["shapes"]:
        for count in manifest["row_counts"] + ([4] if shape["id"] == "constant" else []):
            progressive = count == 4
            shape_id = "progressive" if progressive else shape["id"]
            corpus = f"pending-range-1099-{shape_id}-{count}"
            rows = [[str(i), str(shape["key"])] for i in range(count)]
            if progressive:
                rows.append(["4", "2"])
            source = {"path": str(MANIFEST), "sha256": digest(MANIFEST)}
            corpora.append({"corpus": corpus, "source": source,
                "metadata": {"spark_version": manifest["spark_version"], "timezone": "UTC", "inputs": [
                    {"name": "pending_peers", "schema": {"type": "struct", "fields": fields}, "rows": rows}]},
                "cases": [{"corpus": corpus, "id": f"{shape_id}_{count}", "sql": shape["sql"],
                    "ansi": ansi, "ordered": True, "coverage": {"shape": shape_id, "rows": count}}
                    for ansi in (False, True)]})
    return {"version": 1, "issue": 1099, "spark_version": manifest["spark_version"],
            "spark_revision": manifest["spark_revision"], "expected_record_count": 14, "corpora": corpora}


