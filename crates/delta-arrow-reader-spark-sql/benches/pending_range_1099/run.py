def read(path):
    return json.loads(Path(path).read_text())


def write(path, value):
    Path(path).write_text(json.dumps(value, indent=2, ensure_ascii=True) + "\n")


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def fresh(path):
    path = Path(path).resolve()
    assert not path.is_relative_to(REPO), "generated bytes must stay outside the checkout"
    path.mkdir(parents=True, exist_ok=False)
    return path


def tree_hash(root):
    root = Path(root)
    records = [str(path.relative_to(root)) + "\0" + digest(path)
               for path in sorted(root.rglob("*")) if path.is_file()
               and path.name != "pending-range-1099-assembly.json"]
    return hashlib.sha256("\n".join(records).encode()).hexdigest()


def protocol_hashes():
    return {path.name: digest(path) for path in sorted(HERE.iterdir()) if path.is_file()}


