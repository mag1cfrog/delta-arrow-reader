def load_references(path):
    records = [json.loads(line) for line in Path(path).read_text().splitlines()]
    header = records[0]
    manifest = read(MANIFEST)
    assert header["spark_version"] == manifest["spark_version"]
    assert header["spark_build"]["SPARK_REVISION"]["value"] == manifest["spark_revision"]
    assert header["effective_settings"]["spark.sql.session.timeZone"] == "UTC"
    definitions = {(case["corpus"], case["id"], case["ansi"]): case
                   for corpus in requests()["corpora"] for case in corpus["cases"]}
    assert len(records) == 15 and len(definitions) == 14
    captured = {corpus["corpus"]:corpus for corpus in header["corpora"]}
    assert len(captured) == 7
    for corpus in requests()["corpora"]:
        actual = captured[corpus["corpus"]]
        assert actual["metadata"] == corpus["metadata"]
        assert actual["source"] == corpus["source"]
        assert len(actual["registered_inputs"]) == 1
        provider = actual["registered_inputs"][0]
        assert provider["schema_observed"] == corpus["metadata"]["inputs"][0]["schema"]
        assert provider["num_partitions"] == 1
    seen = set()
    for record in records[1:]:
        key = (record["corpus"], record["id"], record["ansi"])
        assert key not in seen and key in definitions
        seen.add(key)
        assert all(record[name] == definitions[key][name] for name in ("sql", "ordered", "coverage"))
        assert record["effective_settings"]["spark.sql.ansi.enabled"] == str(record["ansi"]).lower()
        assert set(record["schema_stages"]) == {"public", "analyzed", "optimized", "executed_before_collect", "executed"}
        assert all(stage["available"] for stage in record["schema_stage_availability"].values())
        is_error = record["coverage"]["shape"] == "wrapped" and record["ansi"]
        assert record["status"] == ("error" if is_error else "ok")
        if is_error:
            assert record["spark_error_phase"] == "collect"
            assert record["expected"] == {"condition": "ARITHMETIC_OVERFLOW"}
            assert record["spark_error_details"]["cause_chain_complete"]
        else:
            rows = record["expected"]["rows"]
            assert rows == sorted(rows, key=lambda row: int(row[0]))
            assert len(rows) == record["coverage"]["rows"] + (record["coverage"]["shape"] == "progressive")
    assert seen == set(definitions)
    return records


def assemble(destination, observed):
    destination = Path(destination).resolve()
    assert not destination.exists() and not destination.is_relative_to(REPO)
    assert not subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=all"], cwd=REPO, text=True).strip(), "freeze the reviewed protocol in a clean commit first"
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO, text=True).strip()
    subprocess.run(["git", "merge-base", "--is-ancestor", read(MANIFEST)["baseline"], commit], cwd=REPO, check=True)
    destination.mkdir(parents=True)
    with tempfile.TemporaryFile() as archive:
        subprocess.run(["git", "archive", "--format=tar", commit], cwd=REPO, stdout=archive, check=True)
        archive.seek(0)
        with tarfile.open(fileobj=archive) as source:
            source.extractall(destination, filter="data")
    workspace = destination / WORKSPACE.relative_to(REPO)
    generated, anchors = patch_sources() if observed else ({}, [])
    if observed:
        generated[COMMON + "pending_range_1099.rs"] = (HERE / "events.rs").read_text()
    functions = "fn reset_events(_: bool) {}\nfn snapshot_events() -> Value { Value::Null }"
    if observed:
        functions = """fn reset_events(timing: bool) { datafusion::common::pending_range_1099::reset(timing); }
fn snapshot_events() -> Value {
    let (values, pending) = datafusion::common::pending_range_1099::snapshot();
    json!({"counters":values.into_iter().collect::<BTreeMap<_,_>>(),"pending":pending})
}"""
    driver = (HERE / "driver.rs").read_text()
    assert driver.count("// @observations@") == 1
    generated["benches/pending_range_1099/driver.rs"] = driver.replace("// @observations@", functions)
    generated["benches/pending_range_1099_entry.rs"] = """//! Disposable real-executor attribution driver.
#[path = "pending_range_1099/driver.rs"]
mod driver;
#[tokio::main(flavor = "current_thread")]
async fn main() -> Result<(), Box<dyn std::error::Error + Send + Sync>> { driver::run().await }
"""
    generated["Cargo.toml"] = (WORKSPACE / "Cargo.toml").read_text() + '\n[[bench]]\nname = "pending_range_1099"\npath = "benches/pending_range_1099_entry.rs"\nharness = false\n'
    for name, source in generated.items():
        (workspace / name).write_text(source)
    receipt = {"issue":1099,"baseline":read(MANIFEST)["baseline"],"commit":commit,
        "observed":observed,"source":str(destination),"protocol":protocol_hashes(),"anchors":anchors,
        "generated":{name:digest(workspace/name) for name in sorted(generated)},"tree_sha256":tree_hash(destination)}
    write(destination / "pending-range-1099-assembly.json",receipt)


def build(source, target, destination):
    source, target = Path(source).resolve(), Path(target).resolve()
    assert not target.is_relative_to(source) and not target.is_relative_to(REPO)
    destination = fresh(destination)
    assembly = read(source / "pending-range-1099-assembly.json")
    assert tree_hash(source) == assembly["tree_sha256"]
    assert assembly["protocol"] == protocol_hashes()
    workspace = source / WORKSPACE.relative_to(REPO)
    # Match #1390's protection against Cargo fingerprints shared by two source copies.
    for name in set(assembly["generated"]) | set(patch_sources()[0]):
        (workspace / name).touch()
    environment = os.environ.copy()
    for name in ("RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS", "RUSTC_WRAPPER", "RUSTC_WORKSPACE_WRAPPER"):
        assert not environment.get(name), name
    environment.update(RELEASE, CARGO_TARGET_DIR=str(target))
    command = ["cargo", "+1.96.0", "build", "--locked", "--release", "--bench", "pending_range_1099", "--message-format=json-render-diagnostics"]
    with (destination/"build.jsonl").open("x") as output, (destination/"build.stderr").open("x") as errors:
        subprocess.run(command,cwd=workspace,env=environment,stdout=output,stderr=errors,check=True)
    assert tree_hash(source) == assembly["tree_sha256"], "build changed source or lockfile"
    artifacts = [json.loads(line) for line in (destination/"build.jsonl").read_text().splitlines() if line.startswith("{")]
    binaries = [row["executable"] for row in artifacts if row.get("executable") and row.get("target",{}).get("name") == "pending_range_1099"]
    assert len(binaries) == 1
    binary = destination/"pending_range_1099"
    shutil.copy2(binaries[0],binary)
    write(destination/"receipt.json",{"assembly":assembly,"source":str(source),"binary":str(binary),
        "binary_sha256":digest(binary),"compiler_reported_binary":binaries[0],"command":command,
        "environment":dict(RELEASE,CARGO_TARGET_DIR=str(target)),"protocol":protocol_hashes(),
        "rustc":subprocess.check_output(["rustc","+1.96.0","--version","--verbose"],text=True),
        "build_log_sha256":digest(destination/"build.jsonl"),"build_stderr_sha256":digest(destination/"build.stderr")})


def verify_build(path):
    receipt = read(path)
    assert digest(receipt["binary"]) == receipt["binary_sha256"]
    assert tree_hash(receipt["source"]) == receipt["assembly"]["tree_sha256"]
    assert receipt["protocol"] == protocol_hashes()
    return receipt


def invoke(receipt, args, destination, name):
    command = ["taskset","-c",str(read(MANIFEST)["cpu"]),receipt["binary"],*map(str,args)]
    with (destination/(name+".jsonl")).open("x") as output, (destination/(name+".stderr")).open("x") as errors:
        subprocess.run(command,stdout=output,stderr=errors,check=True,timeout=read(MANIFEST)["process_timeout_seconds"])
    return [json.loads(line) for line in (destination/(name+".jsonl")).read_text().splitlines()]


def compare_reference(record, reference):
    actual = record["observation"]
    assert actual["schema_stages"] == reference["schema_stages"], (record["id"],"Fields")
    if reference["status"] == "ok":
        assert actual["error"] is None and actual["phase"] == "encode"
        assert actual["rows"] == reference["expected"]["rows"], (record["id"],"complete rows")
    else:
        assert actual["rows"] is None and actual["phase"] == "collect"
        assert "[ARITHMETIC_OVERFLOW] RANGE comparison target" in actual["error"]
        assert "-2147483648 + -1" in actual["error"], actual["error"]


def work_summary(record):
    before = record["before_eof"]["counters"]
    after = record["after_eof"]["counters"]
    result = {"id":record["id"],"before_eof":before,
        "eof_delta":{name:after[name]-value for name,value in before.items()
                     if not name.startswith("peak_")},
        "peaks":{name:value for name,value in after.items() if name.startswith("peak_")}}
    pending_shape = record["shape"] == "constant" or (record["shape"] == "wrapped" and record["configuration"] == "spark-off")
    if pending_shape:
        count, batch_size = record["rows"], record["batch"]
        batches = count//batch_size
        prefix_work = batch_size*batches*(batches+1)//2
        expected = {"upper_comparisons":prefix_work,"pending_deferrals":batches,
            "input_concat_calls":batches-1,"partition_concat_calls":batches-1,
            "input_copied_rows":prefix_work-batch_size,"partition_copied_rows":prefix_work-batch_size,
            "peak_input_rows":count,"peak_partition_rows":count,"committed_rows":0,
            "accumulator_updated_rows":0}
        result["baseline_predictions_before_eof"] = expected
        result["baseline_prediction_matches"] = {name:before[name] == value for name,value in expected.items()}
        result["baseline_prediction_matches"]["EOF_upper_comparisons"] = after["upper_comparisons"]-before["upper_comparisons"] == count
        assert before["pending_deferrals"] == batches and before["committed_rows"] == 0
        assert before["accumulator_updated_rows"] == 0 and after["accumulator_updated_rows"] == count
        assert after["committed_rows"] == count
        assert batch_size <= before["upper_comparisons"] <= prefix_work
        assert all(row[0] == 0 and row[2:4] == [0,0] and row[4:6] == [0,row[1]]
                   for row in record["before_eof"]["pending"])
    return result


def trace(canonical, observed, reference, destination):
    references = load_references(reference)
    receipts = [verify_build(canonical),verify_build(observed)]
    assert [receipt["assembly"]["observed"] for receipt in receipts] == [False,True]
    assert receipts[0]["assembly"]["commit"] == receipts[1]["assembly"]["commit"]
    destination = fresh(destination)
    arms = [invoke(receipt,["trace",MANIFEST],destination,name)
            for receipt,name in zip(receipts,["canonical","observed"])]
    assert all(len(records) == 63 and len({record["id"] for record in records}) == 63 for records in arms)
    canonical_records = {record["id"]:record for record in arms[0]}
    eligible, excluded = {}, []
    for records in arms:
        for record in records:
            assert record["observation"] == canonical_records[record["id"]]["observation"], record["id"]
            assert record["order_is_column"]
            if record["configuration"] != "native":
                case = next(case for case in references[1:] if case["coverage"]["shape"] == record["shape"]
                    and case["coverage"]["rows"] == record["rows"] and case["ansi"] == (record["configuration"] == "spark-on"))
                compare_reference(record,case)
    for record in arms[0]:
        if record["configuration"] == "native":
            continue
        native_id = record["id"].rsplit(":",1)[0]+":native"
        same = record["observation"] == canonical_records[native_id]["observation"]
        if record["shape"] == "constant":
            assert same, (record["id"],"constant native eligibility")
            eligible[record["id"]] = record["observation"]
            eligible[native_id] = canonical_records[native_id]["observation"]
        elif record["shape"] == "wrapped":
            assert not same, "wrapped native mismatch changed; review eligibility before timing"
            excluded.append({"id":record["id"],"reason":"complete native result or error differs","native_id":native_id})
        else:
            assert record["shape"] == "progressive" and same, (record["id"],"progressive native control")
    assert len(eligible) == 27 and len(excluded) == 18
    for record in arms[1]:
        assert all(not name.endswith("_ns") for name in record["after_eof"]["counters"])
    write(destination/"work.json",[work_summary(record) for record in arms[1]])
    proof = {"issue":1099,"all_spark_matches":True,"reference_sha256":digest(reference),
        "reference":str(Path(reference).resolve()),"protocol":protocol_hashes(),"receipts":receipts,
        "canonical_trace_sha256":digest(destination/"canonical.jsonl"),
        "observed_trace_sha256":digest(destination/"observed.jsonl"),"cases":eligible,"excluded":excluded,
        "native_state":"plain SessionStateBuilder::new().with_default_features(), target_partitions=1, tested batch_size; configure_spark_sql is not installed"}
    write(destination/"eligibility.json",proof)


