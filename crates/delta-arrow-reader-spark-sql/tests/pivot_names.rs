//! Generated PIVOT columns can be selected by the same names as in Spark.

use std::collections::BTreeSet;
use std::sync::Arc;

use arrow::datatypes::DataType;
use datafusion::execution::SessionStateBuilder;
use datafusion::logical_expr::{Volatility, create_udf};
use datafusion::prelude::{SessionConfig, SessionContext};
use delta_arrow_reader_spark_sql::configure_spark_sql;
use serde_json::{Value, json};

#[path = "support/float_inputs.rs"]
mod float_inputs;
use float_inputs::register_float_inputs;
#[path = "support/spark_results.rs"]
mod spark_results;
use spark_results::{TestResult, capture_spark_query_result};

#[tokio::test]
async fn generated_pivot_names_match_spark() -> TestResult {
    let records = include_str!("fixtures/pivot-names-spark.jsonl")
        .lines()
        .map(serde_json::from_str::<Value>)
        .collect::<Result<Vec<_>, _>>()?;
    assert_eq!(records[0]["spark_version"], "4.2.0");
    assert_eq!(records[0]["timezone"], "UTC");
    assert_eq!(records.len() - 1, 270);
    let mut identities = BTreeSet::new();
    for case in &records[1..] {
        assert!(identities.insert((
            case["id"].as_str().ok_or("missing ID")?,
            case["ansi"].as_bool().ok_or("missing ANSI mode")?
        )));
    }
    let mut differences = Vec::new();
    for batch_size in [1, 32] {
        let session = SessionContext::new_with_state(
            configure_spark_sql(
                SessionStateBuilder::new()
                    .with_default_features()
                    .with_config(
                        SessionConfig::new()
                            .with_batch_size(batch_size)
                            .with_target_partitions(2),
                    ),
            )
            .build(),
        );
        register_float_inputs(&session, &records[0], batch_size, 2)?;
        session.register_udf(create_udf(
            "case_udf",
            vec![DataType::Utf8],
            DataType::Utf8,
            Volatility::Immutable,
            Arc::new(|arguments| Ok(arguments[0].clone())),
        ));
        for case in &records[1..] {
            let mut actual = capture_spark_query_result(&session, case)
                .await
                .unwrap_or_else(|error| json!({"error":error.to_string()}));
            let mut expected = case["expected"].clone();
            if case["id"]
                .as_str()
                .is_some_and(|id| id.contains("_projection_"))
            {
                // Ordinary SELECT's generated-alias metadata has its own acceptance in #710.
                remove_spark_generated_alias_marker(&mut expected)?;
                if actual.get("error").is_none() {
                    remove_spark_generated_alias_marker(&mut actual)?;
                }
            }
            if actual != expected {
                differences.push(format!(
                    "{} ANSI={} batch={batch_size}: expected {}, got {actual}",
                    case["id"], case["ansi"], expected
                ));
            }
        }
    }
    assert!(differences.is_empty(), "{}", differences.join("\n"));
    Ok(())
}

fn remove_spark_generated_alias_marker(result: &mut Value) -> TestResult {
    for field in result["schema"]["fields"]
        .as_array_mut()
        .ok_or("missing result fields")?
    {
        if let Some(marker) = field["metadata"]
            .as_object_mut()
            .ok_or("missing metadata")?
            .remove("__autoGeneratedAlias")
        {
            assert_eq!(marker, "true");
        }
    }
    Ok(())
}

#[tokio::test]
async fn native_query_names_are_unchanged() -> TestResult {
    let records = include_str!("fixtures/pivot-names-spark.jsonl")
        .lines()
        .map(serde_json::from_str::<Value>)
        .collect::<Result<Vec<_>, _>>()?;
    let native = SessionContext::new();
    let configured = SessionContext::new_with_state(
        configure_spark_sql(SessionStateBuilder::new().with_default_features()).build(),
    );
    for session in [&native, &configured] {
        register_float_inputs(session, &records[0], 32, 1)?;
    }
    capture_spark_query_result(&configured, &json!({"ansi":true,"sql":
        "SELECT * FROM float_inputs PIVOT(SORT_ARRAY(COLLECT_LIST(CAST(k AS STRING))),MAX(label) AS text FOR (k) IN (CAST('-0.0' AS FLOAT)))"
    })).await?;
    for sql in [
        "SELECT SUM(k),MAX(label) FROM float_inputs",
        "SELECT CAST(k AS VARCHAR),UPPER(label) FROM float_inputs",
    ] {
        let expected = native.sql(sql).await?.collect().await?;
        let actual = configured.sql(sql).await?.collect().await?;
        assert_eq!(actual, expected, "{sql}");
    }
    Ok(())
}
