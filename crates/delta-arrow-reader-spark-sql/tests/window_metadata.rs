#[tokio::test]
async fn derived_window_metadata_matches_spark() -> TestResult {
    let records = include_str!("fixtures/window-metadata-spark.jsonl")
        .lines()
        .map(serde_json::from_str::<Value>)
        .collect::<Result<Vec<_>, _>>()?;
    assert_eq!(records[0]["spark_version"], "4.2.0");
    assert_eq!(records[0]["timezone"], "UTC");
    assert_eq!(records.len() - 1, 102);
    let mut identities = BTreeSet::new();
    for case in &records[1..] {
        assert!(identities.insert((
            case["id"].as_str().ok_or("missing ID")?,
            case["ansi"].as_bool().ok_or("missing ANSI mode")?,
        )));
    }
    let mut differences = Vec::new();
    for batch_size in [1, 32] {
        let session = SessionContext::new_with_state(
            configure_spark_sql(
                SessionStateBuilder::new()
                    .with_default_features()
                    .with_config(
                        SessionConfig::new()
                            .with_batch_size(batch_size)
                            .with_target_partitions(2),
                    ),
            )
            .build(),
        );
        register_recorded_inputs(&session, &records[0], batch_size)?;
        for case in &records[1..] {
            let actual = capture_spark_query_result(&session, case).await;
            let mut expected = case["expected"].clone();
            if case["context"] == "generated" {
                // #710 owns this marker; retain and compare every other metadata entry.
                for field in expected["schema"]["fields"]
                    .as_array_mut()
                    .ok_or("missing fields")?
                {
                    if let Some(marker) = field["metadata"]
                        .as_object_mut()
                        .ok_or("missing metadata")?
                        .remove("__autoGeneratedAlias")
                    {
                        assert_eq!(marker, "true");
                    }
                }
            }
            if actual.as_ref().ok() != Some(&expected) {
                differences.push(format!(
                    "{} ANSI={} batch={batch_size}: expected {expected}, got {actual:?}",
                    case["id"], case["ansi"]
                ));
            }
        }
    }
    assert!(differences.is_empty(), "{}", differences.join("\n"));
    Ok(())
}

#[tokio::test]
async fn window_metadata_keeps_native_sql_unchanged() -> TestResult {
    let metadata: Value = serde_json::from_str(
        include_str!("fixtures/window-metadata-spark.jsonl")
            .lines()
            .next()
            .ok_or("missing metadata")?,
    )?;
    let native = SessionContext::new();
    let configured = SessionContext::new_with_state(
        configure_spark_sql(SessionStateBuilder::new().with_default_features()).build(),
    );
    for session in [&native, &configured] {
        register_recorded_inputs(session, &metadata, 2)?;
    }
    for input in metadata["inputs"].as_array().ok_or("missing inputs")? {
        let table = input["name"].as_str().ok_or("missing table")?;
        let sql = format!(
            "SELECT id,k,LAG(k) OVER w AS lag_result,LEAD(k) OVER w AS lead_result,\
             FIRST_VALUE(k) OVER w AS first_result,LAST_VALUE(k) OVER w AS last_result,\
             NTH_VALUE(k,2) OVER w AS nth_result FROM {table} WINDOW w AS (ORDER BY id)"
        );
        let mut results = Vec::new();
        for session in [&native, &configured] {
            let frame = session.sql(&sql).await?;
            let logical = frame.schema().clone();
            let physical = frame.create_physical_plan().await?;
            for (index, field) in physical.schema().fields().iter().enumerate() {
                assert_eq!(logical.field(index), field.as_ref());
                if index > 0 {
                    assert_eq!(field.metadata().get("purpose"), Some(&"window-key".into()));
                }
            }
            results.push(collect(physical, session.task_ctx()).await?);
        }
        assert_eq!(results[0], results[1], "{sql}");
    }
    Ok(())
}

#[tokio::test]
async fn derived_window_values_preserve_arrow_extension_metadata() -> TestResult {
    let session = SessionContext::new_with_state(
        configure_spark_sql(SessionStateBuilder::new().with_default_features()).build(),
    );
    let extension_metadata = [
        ("ARROW:extension:name".to_owned(), "arrow.json".to_owned()),
        ("ARROW:extension:metadata".to_owned(), "".to_owned()),
    ]
    .into_iter()
    .collect::<std::collections::HashMap<_, _>>();
    let mut input_metadata = extension_metadata.clone();
    input_metadata.insert("purpose".into(), "window-key".into());
    let schema = Arc::new(Schema::new(vec![
        Field::new("id", DataType::Int32, false),
        Field::new("k", DataType::Utf8, true).with_metadata(input_metadata.clone()),
    ]));
    let batch = RecordBatch::try_new(
        schema.clone(),
        vec![
            Arc::new(Int32Array::from(vec![1, 2, 3])),
            Arc::new(StringArray::from(vec![
                Some("{\"n\":1}"),
                None,
                Some("null"),
            ])),
        ],
    )?;
    session.register_table(
        "json_values",
        Arc::new(MemTable::try_new(schema, vec![vec![batch]])?),
    )?;
    for ansi_mode in [true, false] {
        for (function, expected) in [
            ("LAG(k)", json!([null, "{\"n\":1}", null])),
            ("LEAD(k)", json!([null, "null", null])),
            (
                "FIRST_VALUE(k)",
                json!(["{\"n\":1}", "{\"n\":1}", "{\"n\":1}"]),
            ),
            ("LAST_VALUE(k)", json!(["{\"n\":1}", null, "null"])),
            ("NTH_VALUE(k,2)", json!([null, null, null])),
            ("FIRST(k)", json!(["{\"n\":1}", "{\"n\":1}", "{\"n\":1}"])),
            ("LAST(k)", json!(["{\"n\":1}", null, "null"])),
            (
                "ANY_VALUE(k)",
                json!(["{\"n\":1}", "{\"n\":1}", "{\"n\":1}"]),
            ),
        ] {
            let sql = format!(
                "SELECT * FROM (SELECT id,k,{function} OVER (ORDER BY id) AS derived_value \
                 FROM json_values) derived ORDER BY id"
            );
            let query = plan_query(
                &session,
                &sql,
                &SparkSqlOptions {
                    ansi_mode,
                    ..SparkSqlOptions::default()
                },
            )
            .await?;
            let physical = query.create_physical_plan(&session).await?;
            for (index, field) in physical.schema().fields().iter().enumerate() {
                let logical = query.logical_plan.schema().field(index);
                assert_eq!(logical.data_type(), field.data_type());
                assert_eq!(logical.is_nullable(), field.is_nullable());
                assert_eq!(logical.metadata(), field.metadata());
                if index == 1 {
                    assert_eq!(field.metadata(), &input_metadata);
                } else if index == 2 {
                    assert_eq!(field.metadata(), &extension_metadata);
                    assert_eq!(field.data_type(), &DataType::Utf8);
                    assert!(field.is_nullable());
                }
            }
            let mut actual = Vec::new();
            for batch in collect(physical, session.task_ctx()).await? {
                let values = batch
                    .column(2)
                    .as_any()
                    .downcast_ref::<StringArray>()
                    .ok_or("expected JSON strings")?;
                actual.extend(values.iter().map(|value| json!(value)));
            }
            assert_eq!(json!(actual), expected, "{sql} ANSI={ansi_mode}");
        }
    }
    Ok(())
}
